/**
 * Generates supabase/catalog.sql from the bundled product catalog so the real shop inventory can be
 * loaded into Supabase once:   npx tsx scripts/generate-catalog-sql.ts

 * Ratings/reviews are zeroed on purpose (demo values are not real customer reviews).
 * The SQL is idempotent (ON CONFLICT (slug) DO NOTHING) so it never overwrites admin edits.
 */
import { writeFileSync } from 'node:fs'
import { MOCK_PRODUCTS } from '../src/lib/mock-products'

const q = (v: string) => `'${v.replace(/'/g, "''")}'`
const num = (n: number | undefined | null) => (n === undefined || n === null ? 'NULL' : String(n))
const json = (v: unknown) => (v === undefined ? 'NULL' : `${q(JSON.stringify(v))}::jsonb`)

const rows = MOCK_PRODUCTS.map((p) =>
  `(${q(p.slug)}, ${q(p.name)}, ${q(p.description ?? '')}, ${num(p.price)}, ${num(p.salePrice)}, ${q(p.category)}, ` +
  `'[]'::jsonb, ${p.inStock}, ${num(p.stockCount)}, 0, 0, ${p.featured}, ` +
  `${json(p.variants)}, ${json(p.specs)})`,
)

const sql = `-- Generated by scripts/generate-catalog-sql.ts — ${rows.length} products. Safe to re-run.
INSERT INTO public.products
  (slug, name, description, price, sale_price, category, images, in_stock, stock_count, rating, review_count, featured, variants, specs)
VALUES
${rows.join(',\n')}
ON CONFLICT (slug) DO NOTHING;
`
writeFileSync(new URL('../supabase/catalog.sql', import.meta.url), sql)
console.log(`Wrote supabase/catalog.sql with ${rows.length} products`)
